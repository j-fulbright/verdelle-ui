//! Turns shadcn-format theme CSS files into verdelle-ui's selectable themes: a stylesheet
//! (`tokens.css`) with one `[data-theme="<name>"]` block per theme, and a Rust list of them
//! (`themes.rs`) for the theme switcher.
//!
//! To add a theme, export one from a shadcn theme tool (tweakcn, shadcn/create, the docs'
//! theme pages), save the CSS as `<name>.css` in a themes folder, and run this example.
//! `neutral.css` is required: it is the default theme.
//!
//! ```text
//! cargo run -p verdelle-ui --example themegen                      # rebuild verdelle-ui's own themes
//! cargo run -p verdelle-ui --example themegen -- --check           # fail if they are stale (CI)
//! cargo run -p verdelle-ui --example themegen -- --themes my-themes --out src/generated
//! ```
//!
//! With `--themes <dir>` the themes are read from that folder instead of verdelle-ui's own
//! `themes/`; with `--out <dir>` the output is `<dir>/tokens.css` and `<dir>/themes.rs`
//! instead of replacing verdelle-ui's own generated files.

use anyhow::{Context, Result, bail};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use verdelle_ui::theme_css::{Decls, parse_theme_css};

const DEFAULT_THEME: &str = "neutral";

struct Theme {
    slug: String,
    name: String,
    /// The source file's name, for the `include_str!` in the generated list.
    file: String,
    light: Decls,
    dark: Option<Decls>,
}

/// `tokyo-night.css` -> slug `tokyo-night`, name `Tokyo Night`.
fn identify(path: &Path) -> Result<(String, String)> {
    let stem = path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or_default();
    let mut slug = String::new();
    for c in stem.chars() {
        if c.is_ascii_alphanumeric() {
            slug.push(c.to_ascii_lowercase());
        } else if !slug.ends_with('-') && !slug.is_empty() {
            slug.push('-');
        }
    }
    let slug = slug.trim_end_matches('-').to_string();
    if slug.is_empty() {
        bail!("cannot derive a theme name from {}", path.display());
    }
    let name = slug
        .split('-')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect::<Vec<_>>()
        .join(" ");
    Ok((slug, name))
}

fn load(dir: &Path) -> Result<Vec<Theme>> {
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)
        .with_context(|| format!("reading {}", dir.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "css"))
        .collect();
    files.sort();

    let mut themes: Vec<Theme> = Vec::new();
    for f in files {
        let (slug, name) = identify(&f)?;
        if themes.iter().any(|t| t.slug == slug) {
            bail!("two theme files map to the name {slug:?}");
        }
        let css = std::fs::read_to_string(&f)?;
        let parsed = parse_theme_css(&css)
            .map_err(|e| anyhow::anyhow!(e))
            .with_context(|| format!("parsing {}", f.display()))?;
        if parsed.dark.is_none() {
            eprintln!(
                "warning: {} has no `.dark` block; dark mode will keep its light colors",
                f.display()
            );
        }
        themes.push(Theme {
            slug,
            name,
            file: f
                .file_name()
                .and_then(|n| n.to_str())
                .unwrap_or_default()
                .to_string(),
            light: parsed.light,
            dark: parsed.dark,
        });
    }
    if !themes.iter().any(|t| t.slug == DEFAULT_THEME) {
        bail!(
            "the default theme {DEFAULT_THEME}.css is missing from {}",
            dir.display()
        );
    }
    Ok(themes)
}

fn decls(out: &mut String, decls: &Decls) {
    for (k, v) in decls {
        let _ = writeln!(out, "  {k}: {v};");
    }
}

/// The popups the menu colour option can invert (`data-vdl-menu-color` on `<html>`): they get
/// the dark tokens whatever the page mode, as shadcn adds `dark` to its `cn-menu-target`s.
const MENU_SURFACES: &str = ".vdl-menu, .vdl-select__content, .vdl-combobox__content";
const INVERTED: &str = "[data-vdl-menu-color^=\"inverted\"]";

/// `themes_rel` is the path from the generated Rust file to the themes folder, for `include_str!`;
/// `tokens_rel` is the path from it to the generated stylesheet.
fn render(themes: &[Theme], themes_rel: &str, tokens_rel: &str) -> (String, String) {
    let default = themes
        .iter()
        .find(|t| t.slug == DEFAULT_THEME)
        .expect("checked in load");

    let mut css = String::from(
        "/* @generated by `cargo run -p verdelle-ui --example themegen`. Do not edit.\n   \
         Source: themes/*.css (shadcn format). To add a theme, drop its CSS in themes/ and re-run.\n   \
         Mode is the `.dark` class on <html>; the theme is `data-theme=\"<name>\"` on <html>. */\n\n\
         /* Default theme (no data-theme): neutral. */\n:root {\n",
    );
    decls(&mut css, &default.light);
    css.push_str("}\n");
    if let Some(dark) = &default.dark {
        let _ = writeln!(css, ".dark,\n:root{INVERTED} :is({MENU_SURFACES}) {{");
        decls(&mut css, dark);
        css.push_str("}\n");
    }

    // One pair of blocks per theme. The `.dark ... [data-theme]` forms also cover an
    // element that sets its own data-theme inside a dark page (the theme picker's cards).
    for t in themes {
        let _ = writeln!(css, "\n/* {} */\n[data-theme=\"{}\"] {{", t.name, t.slug);
        decls(&mut css, &t.light);
        css.push_str("}\n");
        if let Some(dark) = &t.dark {
            let _ = writeln!(
                css,
                ".dark[data-theme=\"{0}\"],\n.dark [data-theme=\"{0}\"],\n\
                 :root[data-theme=\"{0}\"]{INVERTED} :is({MENU_SURFACES}) {{",
                t.slug
            );
            decls(&mut css, dark);
            css.push_str("}\n");
        }
    }

    let mut rs = String::from(
        "// @generated by `cargo run -p verdelle-ui --example themegen`. Do not edit.\n\
         #![cfg_attr(rustfmt, rustfmt::skip)]\n\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub struct ThemeInfo {\n    pub slug: &'static str,\n    pub name: &'static str,\n    /// The theme's shadcn-format CSS (`:root` and `.dark` blocks), for composing presets.\n    pub source: &'static str,\n}\n\n\
         /// The theme used when none is chosen (`:root` in tokens.css).\n\
         pub const DEFAULT_THEME: &str = \"neutral\";\n\n\
         /// The generated stylesheet, for injecting from Rust instead of importing `css/kit.css`.\n\
         pub const TOKENS_CSS: &str = include_str!(\"{tokens_rel}\");\n\n\
         /// Every theme, selected with `data-theme=\"<slug>\"` on `<html>`.\n\
         /// Light or dark is the separate `.dark` class on `<html>`.\n\
         pub const THEMES: &[ThemeInfo] = &[\n",
    )
    .replace("{tokens_rel}", tokens_rel);
    for t in themes {
        let _ = writeln!(
            rs,
            "    ThemeInfo {{ slug: {:?}, name: {:?}, source: include_str!({:?}) }},",
            t.slug,
            t.name,
            format!("{themes_rel}/{}", t.file)
        );
    }
    rs.push_str("];\n");
    (css, rs)
}

/// The value after `--name`, if given.
fn option(name: &str) -> Option<PathBuf> {
    let args: Vec<String> = std::env::args().collect();
    let at = args.iter().position(|a| a == name)?;
    args.get(at + 1).map(PathBuf::from)
}

/// The path from directory `from` to directory `to`, with `/` separators, for `include_str!`.
fn relative(from: &Path, to: &Path) -> String {
    let abs = |p: &Path| std::fs::canonicalize(p).unwrap_or_else(|_| p.to_path_buf());
    let (from, to) = (abs(from), abs(to));
    let f: Vec<_> = from.components().collect();
    let t: Vec<_> = to.components().collect();
    let common = f.iter().zip(&t).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<String> = vec!["..".to_string(); f.len() - common];
    parts.extend(
        t[common..]
            .iter()
            .map(|c| c.as_os_str().to_string_lossy().into_owned()),
    );
    parts.join("/")
}

fn main() -> Result<()> {
    let check = std::env::args().any(|a| a == "--check");
    let kit = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let themes_dir = option("--themes").unwrap_or_else(|| kit.join("themes"));
    let themes = load(&themes_dir)?;
    let outputs = match option("--out") {
        // Outside verdelle-ui the stylesheet sits next to the Rust file.
        Some(out) => {
            if !check {
                std::fs::create_dir_all(&out)?;
            }
            let rel = relative(&out, &themes_dir);
            let (css, rs) = render(&themes, &rel, "tokens.css");
            [(out.join("tokens.css"), css), (out.join("themes.rs"), rs)]
        }
        None => {
            let (css, rs) = render(&themes, "../themes", "../css/tokens.css");
            [
                (kit.join("css/tokens.css"), css),
                (kit.join("src/themes.rs"), rs),
            ]
        }
    };

    let mut stale = false;
    for (path, content) in &outputs {
        if check {
            if std::fs::read_to_string(path).ok().as_deref() != Some(content.as_str()) {
                eprintln!("stale: {}", path.display());
                stale = true;
            }
        } else {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)?;
            }
            std::fs::write(path, content)?;
            println!("wrote {} ({} bytes)", path.display(), content.len());
        }
    }
    if stale {
        bail!("generated files are out of date; run `cargo run -p verdelle-ui --example themegen`");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_come_from_file_names() {
        let (slug, name) = identify(Path::new("themes/Tokyo_Night.css")).unwrap();
        assert_eq!(
            (slug.as_str(), name.as_str()),
            ("tokyo-night", "Tokyo Night")
        );
        assert!(identify(Path::new("themes/---.css")).is_err());
    }

    #[test]
    fn relative_paths_walk_up_and_down() {
        let tmp = std::env::temp_dir();
        let a = tmp.join("themegen-rel-a/out");
        let b = tmp.join("themegen-rel-b/themes");
        std::fs::create_dir_all(&a).unwrap();
        std::fs::create_dir_all(&b).unwrap();
        assert_eq!(relative(&a, &b), "../../themegen-rel-b/themes");
        assert_eq!(relative(&a, &a), "");
    }

    #[test]
    fn renders_default_and_scoped_blocks() {
        let theme = |slug: &str, dark: bool| Theme {
            slug: slug.into(),
            name: slug.into(),
            file: format!("{slug}.css"),
            light: vec![("--background".into(), "white".into())],
            dark: dark.then(|| vec![("--background".into(), "black".into())]),
        };
        let (css, rs) = render(
            &[theme("neutral", true), theme("rose", false)],
            "../themes",
            "../css/tokens.css",
        );
        assert!(css.contains(":root {\n  --background: white;"));
        assert!(css.contains(".dark,\n:root[data-vdl-menu-color^=\"inverted\"] :is("));
        assert!(css.contains(") {\n  --background: black;"));
        assert!(css.contains("[data-theme=\"rose\"] {\n  --background: white;"));
        assert!(css.contains(".dark[data-theme=\"neutral\"],\n.dark [data-theme=\"neutral\"],\n"));
        assert!(
            css.contains(":root[data-theme=\"neutral\"][data-vdl-menu-color^=\"inverted\"] :is(")
        );
        // A theme with no dark block gets no dark rule.
        assert!(!css.contains("data-theme=\"rose\"],\n.dark"));
        assert!(rs.contains(
            "ThemeInfo { slug: \"rose\", name: \"rose\", source: include_str!(\"../themes/rose.css\") }"
        ));
        assert!(rs.contains("include_str!(\"../css/tokens.css\")"));
    }
}
